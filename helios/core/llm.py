"""HELIOS Multi-Provider LLM Integration Layer.

Supports offline deterministic mock generation (for air-gapped accelerator control nets
and CI testing), local LLM endpoints (Ollama, vLLM), OpenAI-compatible servers, and Google Gemini.
Includes structured tool calling and intent parsing.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
import json
import logging
import os
import re
from typing import Any, Callable, Dict, List, Optional
from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)


class ToolCall(BaseModel):
    """Structured tool / function invocation generated by LLM."""
    name: str
    arguments: Dict[str, Any] = Field(default_factory=dict)
    call_id: Optional[str] = None


class LLMMessage(BaseModel):
    """Chat message in LLM conversation history."""
    role: str = Field(..., description="'system', 'user', 'assistant', or 'tool'")
    content: str = ""
    tool_calls: Optional[List[ToolCall]] = None
    tool_call_id: Optional[str] = None


class LLMResponse(BaseModel):
    """Standardized response from an LLM invocation."""
    content: str = ""
    tool_calls: List[ToolCall] = Field(default_factory=list)
    model: str = "unknown"
    usage: Dict[str, int] = Field(default_factory=dict)


class BaseLLMClient(ABC):
    """Abstract interface for LLM client providers."""

    @abstractmethod
    def generate(
        self,
        messages: List[LLMMessage],
        tools: Optional[List[Dict[str, Any]]] = None,
        temperature: float = 0.0,
    ) -> LLMResponse:
        """Synchronously generate LLM response given conversation history and optional tools."""


class MockLLMClient(BaseLLMClient):
    """Deterministic, offline LLM client for testing and air-gapped linac control environments.

    Parses natural language prompts with physics-informed regex rules to synthesize
    appropriate structured tool calls or plan generation responses.
    """

    def __init__(self, model_name: str = "mock-helios-planner"):
        self.model_name = model_name

    def generate(
        self,
        messages: List[LLMMessage],
        tools: Optional[List[Dict[str, Any]]] = None,
        temperature: float = 0.0,
    ) -> LLMResponse:
        # Find last user prompt
        last_user_msg = ""
        for m in reversed(messages):
            if m.role == "user":
                last_user_msg = m.content
                break

        query = last_user_msg.lower()

        # Rule 1: Orbit correction intent
        if any(w in query for w in ["orbit", "trajectory", "steerer", "flatten", "bpm"]):
            # Find section
            sec = "MEBT"
            if "lebt" in query:
                sec = "LEBT"
            elif "scl" in query:
                sec = "SCL"

            tool_call = ToolCall(
                name="formulate_orbit_plan",
                arguments={
                    "section": sec,
                    "target_rms_mm": 0.3,
                    "steerers": [f"{sec}_CH01"],
                    "bpms": [f"{sec}_BPM01", f"{sec}_BPM02"],
                    "rationale": "Automated response matrix SVD correction proposed by planner agent.",
                },
                call_id="call_mock_orbit_01",
            )
            return LLMResponse(
                content=f"I analyzed your request to correct the orbit in {sec}. I recommend generating an SVD orbit correction plan using dipole steerers.",
                tool_calls=[tool_call],
                model=self.model_name,
            )

        # Rule 2: RF cavity phase/amplitude scan intent
        elif any(w in query for w in ["cavity", "rf", "phase", "buncher", "amplitude"]):
            tool_call = ToolCall(
                name="formulate_rf_scan_plan",
                arguments={
                    "cavity_name": "MEBT_CAV01",
                    "scan_parameter": "phase",
                    "start_val": -180.0,
                    "stop_val": 180.0,
                    "step_val": 30.0,
                    "rationale": "Scan RF phase to locate synchronous phase point with maximum energy gain.",
                },
                call_id="call_mock_rf_01",
            )
            return LLMResponse(
                content="I recommend performing an automated RF cavity phase scan across [-180, 180] degrees to calibrate the synchronous phase.",
                tool_calls=[tool_call],
                model=self.model_name,
            )

        # Rule 3: Beam loss / anomaly diagnosis intent
        elif any(w in query for w in ["loss", "blm", "trip", "radiation", "interlock", "fault"]):
            tool_call = ToolCall(
                name="diagnose_linac_anomalies",
                arguments={
                    "section": "MEBT",
                    "check_interlocks": True,
                    "rationale": "Inspect BLM radiation dose rates and verify MPS interlock clearance.",
                },
                call_id="call_mock_diag_01",
            )
            return LLMResponse(
                content="Identified beam loss / anomaly concern. Querying real-time BLM diagnostics and MPS interlock status.",
                tool_calls=[tool_call],
                model=self.model_name,
            )

        # Default fallback
        return LLMResponse(
            content=f"HELIOS Orchestrator received directive: '{last_user_msg}'. Ready to execute planning or diagnostic workflows.",
            tool_calls=[],
            model=self.model_name,
        )


class OpenAICompatibleLLMClient(BaseLLMClient):
    """Connects to OpenAI-compatible endpoints (Ollama, vLLM, LocalAI, OpenAI API)."""

    def __init__(
        self,
        base_url: Optional[str] = None,
        api_key: Optional[str] = None,
        model: str = "gpt-4o-mini",
        timeout_seconds: float = 30.0,
    ):
        self.base_url = (base_url or os.environ.get("OPENAI_BASE_URL", "https://api.openai.com/v1")).rstrip("/")
        self.api_key = api_key or os.environ.get("OPENAI_API_KEY", "")
        self.model = model
        self.timeout = timeout_seconds

    def generate(
        self,
        messages: List[LLMMessage],
        tools: Optional[List[Dict[str, Any]]] = None,
        temperature: float = 0.0,
    ) -> LLMResponse:
        import urllib.request
        import urllib.error

        payload: Dict[str, Any] = {
            "model": self.model,
            "messages": [m.model_dump(exclude_none=True) for m in messages],
            "temperature": temperature,
        }
        if tools:
            payload["tools"] = tools

        headers = {
            "Content-Type": "application/json",
        }
        if self.api_key:
            headers["Authorization"] = f"Bearer {self.api_key}"

        req = urllib.request.Request(
            f"{self.base_url}/chat/completions",
            data=json.dumps(payload).encode("utf-8"),
            headers=headers,
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                data = json.loads(resp.read().decode("utf-8"))

            choice = data["choices"][0]["message"]
            content = choice.get("content") or ""
            tool_calls = []

            for tc in choice.get("tool_calls", []):
                fn = tc.get("function", {})
                args = json.loads(fn.get("arguments", "{}"))
                tool_calls.append(ToolCall(
                    name=fn.get("name", ""),
                    arguments=args,
                    call_id=tc.get("id"),
                ))

            return LLMResponse(
                content=content,
                tool_calls=tool_calls,
                model=data.get("model", self.model),
                usage=data.get("usage", {}),
            )
        except Exception as e:
            logger.error(f"Error calling OpenAI-compatible LLM at {self.base_url}: {e}")
            raise


def create_llm_client(provider: str = "mock", **kwargs) -> BaseLLMClient:
    """Factory creating configured LLM client instance."""
    provider_clean = provider.lower()
    if provider_clean in ("mock", "offline"):
        return MockLLMClient(**kwargs)
    elif provider_clean in ("openai", "ollama", "vllm", "local"):
        return OpenAICompatibleLLMClient(**kwargs)
    else:
        logger.warning(f"Unknown provider '{provider}', defaulting to MockLLMClient.")
        return MockLLMClient(**kwargs)
