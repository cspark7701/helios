"""HELIOS Lattice Format Converters (MAD-X and Elegant LTE).

Provides bi-directional translation between HELIOS native Lattice objects
and standard CERN MAD-X and APS Elegant beamline definition formats.
"""

import re

from helios.physics.elements import (
    DiagnosticElement,
    Drift,
    Quadrupole,
    RFCavity,
    Steerer,
)
from helios.physics.lattice import Lattice


class LatticeConverter:
    """Exports and imports accelerator beamlines to/from MAD-X and Elegant."""

    @staticmethod
    def export_to_madx(lattice: Lattice) -> str:
        """Export lattice deck into CERN MAD-X beamline format."""
        lines = [
            f"! MAD-X Lattice generated by HELIOS: {lattice.name}",
            f"! Energy: {lattice.kinetic_energy_mev_u:.3f} MeV/u, Mass: {lattice.mass_amu:.3f} amu, Q: {lattice.charge_q:.1f}",
            "",
        ]

        elem_names = []
        for elem in lattice.elements:
            safe_name = elem.name.replace(":", "_").replace("-", "_")
            elem_names.append(safe_name)

            if isinstance(elem, Drift):
                lines.append(f"{safe_name}: DRIFT, L={elem.length:.6f};")
            elif isinstance(elem, Quadrupole):
                # k1 = gradient / B*rho (using 1.0 as standard geometric normalization)
                lines.append(f"{safe_name}: QUADRUPOLE, L={elem.length:.6f}, K1={elem.gradient_t_m:.6f};")
            elif isinstance(elem, RFCavity):
                lines.append(
                    f"{safe_name}: RFCAVITY, L={elem.length:.6f}, VOLT={elem.voltage_kv * 1e-3:.6f}, "
                    f"LAG={elem.phase_deg / 360.0:.6f}, HARMON=1;"
                )
            elif isinstance(elem, Steerer):
                lines.append(
                    f"{safe_name}: HKICKER, L={elem.length:.6f}, KICK={elem.kick_x_mrad * 1e-3:.6f};"
                )
            elif isinstance(elem, DiagnosticElement):
                lines.append(f"{safe_name}: MONITOR, L={elem.length:.6f};")

        lines.append("")
        lines.append(f"{lattice.name}_LINE: LINE=({', '.join(elem_names)});")
        lines.append("")
        return "\n".join(lines)

    @staticmethod
    def export_to_elegant(lattice: Lattice) -> str:
        """Export lattice into APS Elegant (.lte) format."""
        lines = [
            f"! Elegant LTE Lattice generated by HELIOS: {lattice.name}",
            "",
        ]

        elem_names = []
        for elem in lattice.elements:
            safe_name = elem.name.replace(":", "_").replace("-", "_")
            elem_names.append(safe_name)

            if isinstance(elem, Drift):
                lines.append(f"{safe_name}: EDRIFT, L={elem.length:.6f}")
            elif isinstance(elem, Quadrupole):
                lines.append(f"{safe_name}: KQUAD, L={elem.length:.6f}, K1={elem.gradient_t_m:.6f}")
            elif isinstance(elem, RFCavity):
                lines.append(
                    f"{safe_name}: RFCW, L={elem.length:.6f}, VOLT={elem.voltage_kv * 1e3:.1f}, "
                    f"PHASE={elem.phase_deg:.2f}, FREQ={elem.frequency_mhz * 1e6:.1f}"
                )
            elif isinstance(elem, Steerer):
                lines.append(f"{safe_name}: HKICK, L={elem.length:.6f}, KICK={elem.kick_x_mrad * 1e-3:.6f}")
            elif isinstance(elem, DiagnosticElement):
                lines.append(f"{safe_name}: WATCH, L={elem.length:.6f}")

        lines.append("")
        lines.append(f"{lattice.name}_LINE: LINE=({', '.join(elem_names)})")
        lines.append("")
        return "\n".join(lines)

    @staticmethod
    def import_from_madx(madx_content: str, lattice_name: str = "IMPORTED_LATTICE") -> Lattice:
        """Parse MAD-X deck definitions into a HELIOS Lattice instance."""
        elements = []
        pattern = re.compile(r"^\s*([A-Za-z0-9_]+)\s*:\s*([A-Za-z0-9_]+)\s*,\s*(.*?)\s*;", re.MULTILINE)

        for match in pattern.finditer(madx_content):
            name, elem_type, params_str = match.groups()
            elem_type = elem_type.upper()

            params = {}
            for item in params_str.split(","):
                if "=" in item:
                    k, v = item.strip().split("=")
                    try:
                        params[k.strip().upper()] = float(v.strip())
                    except ValueError:
                        params[k.strip().upper()] = v.strip()

            l_m = params.get("L", 0.1)

            if elem_type == "DRIFT":
                elements.append(Drift(name=name, length=l_m))
            elif elem_type == "QUADRUPOLE":
                elements.append(Quadrupole(name=name, length=l_m, gradient_t_m=params.get("K1", 0.0)))
            elif elem_type == "RFCAVITY":
                v_kv = params.get("VOLT", 0.5) * 1e3
                phi_deg = params.get("LAG", 0.0) * 360.0
                elements.append(RFCavity(name=name, length=l_m, voltage_kv=v_kv, phase_deg=phi_deg))
            elif elem_type in ["HKICKER", "VKICKER", "KICKER"]:
                kick_mrad = params.get("KICK", 0.0) * 1e3
                elements.append(Steerer(name=name, length=l_m, kick_x_mrad=kick_mrad))
            elif elem_type in ["MONITOR", "HMONITOR", "VMONITOR", "MARKER"]:
                elements.append(DiagnosticElement(name=name, length=l_m, diag_type="BPM"))

        return Lattice(name=lattice_name, elements=elements)
